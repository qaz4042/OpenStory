    inline const char* text(Key key, std::string_view language)
    {
        auto index = static_cast<unsigned>(key);
        if (index >= static_cast<unsigned>(Key::Count)) return "";
        const auto& message = messages[index];
        return language == "zh-CN" && message.zh[0] ? message.zh : message.en;
    }

    inline const char* normalize(std::string_view language)
    {
        return language == "zh-CN" ? "zh-CN" : "en";
    }
